"""猫和狗各自的剖面规格。

这份文件是 docs/06 §5.1 那张差异表的可执行版本：

| 部位 | 猫 | 狗 |
| --- | --- | --- |
| 耳朵 | 尖立三角 | 垂耳或半垂 |
| 脸型 | 圆脸、短吻 | 略长吻部 |
| 尾巴 | 细长上翘 | 短粗或卷曲 |
| 体态 | 纤细 | 敦实 |

**只有网格剪影和贴图分区能不一样，骨架必须逐根一致**（§5.1）。共用骨架
是整个成本模型的地基：动画只做一套、配饰只做一套。所以这里不许出现任何
骨骼坐标——骨架只有 `rig_spec.py` 一份。

坐标全部是 Cocos 空间（Y 上、Z 前），单位是骨架的规格尺度，
导出前统一乘 `rig_spec.RIG_SCALE`。

## 两条硬约束，改造型时先看这里

**猫狗必须等高（§5.2「猫狗等高、共用比例」），而且都是 2.0 单位（§5.3）。**
相机构图按 2.0 定的，一高一矮就要为每个物种重调相机。

这条正好卡住垂耳：狗如果做成全垂耳，最高点就变成头顶，比猫的尖耳矮一档。
所以狗用**半垂**——耳朵先立起来到猫耳尖那个高度，再折下来挂在头侧。
§5.1 原文是「垂耳**或半垂**」，半垂合规，而且从正面看那对下垂的耳廓
是最强的犬类信号。

**眼高、肩高、脚底线要对齐**（§5.2 三视图基准线）。挂点位置一致靠的是骨架，
但眼睛和吻部这类不挂骨骼的造型件，两个物种也要落在同一条水平线上，
否则同一顶帽子、同一条围巾在两只身上会一高一低。
"""


# 眼球的网格分辨率。默认那档（build_skeleton.SPHERE_SEGMENTS，十段六环）
# 在脸上读成一个**八边形**——眼睛是全脸唯一被反复注视的地方，轮廓一带棱角，
# Q 版的可爱度立刻掉光。这是花两百多个面就能买到的，代价从身体的融合预算里出：
# 身体是个光滑的团，少 100 面看不出来。
EYE_RES = (16, 10)


def sphere(bone, material, center, radii, res=None):
    """`res` 是 (经线段数, 环数)，只有需要更圆的形体才传，默认走全局那档。"""
    return ("sphere", bone, material, (center, radii, res))


def taper(bone, material, p0, p1, r0, r1, squash=None):
    """两点之间的锥台。垂耳、弯尾、四肢都靠它——球串不出这些形状。

    `squash` 是 (x, y, z) 逐轴压扁系数。耳朵必须压 **Z**：相机固定在正前方，
    耳廓要正对镜头才有面积，压 X 的话镜头只看到侧棱，像两根天线。
    """
    return ("taper", bone, material, (p0, p1, r0, r1, squash))


# 躯干三段互相交叠，融合后是一个连贯的圆桶身。
# 敦实 / 纤细的差别就在这三个半轴上，狗比猫粗约一成。
def _torso(scale):
    return [
        sphere("hips",     "pet_body", (0.00, 0.56, -0.18),
               (0.33 * scale, 0.31 * scale, 0.30 * scale)),
        sphere("spine_01", "pet_body", (0.00, 0.59,  0.03),
               (0.34 * scale, 0.32 * scale, 0.30 * scale)),
        sphere("spine_02", "pet_body", (0.00, 0.62,  0.19),
               (0.31 * scale, 0.29 * scale, 0.27 * scale)),
        sphere("neck",     "pet_body", (0.00, 0.76,  0.22),
               (0.195 * scale, 0.17 * scale, 0.185 * scale)),
    ]


def _skin_graph(nodes, chains):
    """Skin 修改器的输入：一张「顶点 + 边 + 每点粗细」的骨架图。

    `nodes` 是 {名字: (位置, 半径)}，`chains` 是若干条顶点名序列，
    相邻两个之间连一条边。同一个名字出现在多条链里就是分叉点
    （比如 spine_02 同时接头、左前腿、右前腿），Skin 会在那里生成一个过渡的枢纽。

    比「摆一堆球再体素重构」好在哪：出来是连续的四边形表面，关节处是真的过渡
    而不是两个球泡在一起，而且有边流——UV 密度才可能均匀。
    """
    return {"nodes": nodes, "chains": chains}


def _leg_chain(prefix, hip, knee, ankle, paw, radii):
    """一条腿的四个节点。paw 的底面要正好落在 y=0 上（§5.3 原点在脚底）。"""
    r_hip, r_knee, r_ankle, r_paw = radii
    return {
        prefix + "_hip":   (hip, r_hip),
        prefix + "_knee":  (knee, r_knee),
        prefix + "_ankle": (ankle, r_ankle),
        prefix + "_paw":   (paw, r_paw),
    }


def _paws(size, front_z=0.18, back_z=-0.18):
    return [
        sphere("paw_front_L", "pet_body", ( 0.16, 0.07, front_z), size),
        sphere("paw_front_R", "pet_body", (-0.16, 0.07, front_z), size),
        sphere("paw_back_L",  "pet_body", ( 0.15, 0.07, back_z), size),
        sphere("paw_back_R",  "pet_body", (-0.15, 0.07, back_z), size),
    ]


def _face(eye, eye_r, nose, nose_r, mouth, cheek, cheek_r):
    """五官。返回四份数据：网格、贴图分区色、五官顶点取色、眼球贴花规格。

    这里是「好看」的主战场。宠物在屏幕上只有两百多像素，身体占了大部分面积，
    但玩家的注意力全在脸上——脸上少一样东西，观感的损失远大于身体上少一样。

    眼睛必须明显凸出球面，埋进去只会读成两个洞。
    眼球本身是**独立几何**（§5.2 的要求，换装和遮挡才可控），
    但眼廓 / 虹膜 / 瞳孔 / 星形高光这四层全部烘进贴图——加套嵌的球体要多
    400 面，3000 的预算给不起，而这四层恰恰是「有神」和「死鱼眼」的分界。

    贴图能精确落位的原因见 `make_eye_texture.py`：眼球是个球，中心和半径
    就是下面这几个数，沿光轴平面投影，哪个像素落在球面哪一点完全确定。
    """
    ex, ey, ez = eye
    mx, my, mz = mouth
    cx, cy, cz = cheek

    # 眼球的光轴：贴花沿这条轴平面投影上去，星形高光落在轴心附近。
    #
    # 这条轴几乎是正前方，不是「从头中心指向眼球」。按头中心那版算出来是
    # (0.36, 0.16, 0.92)，两只眼各自朝外偏，看着像斜视。
    # 正对镜头的瞳孔会让玩家觉得宠物在看自己，这是观感上极便宜的一大笔。
    axis = (0.14, 0.09, 0.99)
    alen = sum(c * c for c in axis) ** 0.5
    axis = tuple(c / alen for c in axis)

    # 眼球是一颗光球，图案全靠贴花。
    #
    # 之前用几何堆过两轮，都是死路：一片凸出的瞳孔圆盘 + 一颗毛色小球当高光。
    # 圆盘凸出量再压也像贴了个镜片，再加一层虹膜盘就叠成了年轮；
    # 而那颗高光小球是 `pet_body` 材质、要参与体素重构，融进头以后
    # 在眼角上鼓出一个疙瘩，白点却几乎看不见。
    #
    # 真正的原因是 `pet_detail` 那个材质球在烘焙时根本没接顶点色，
    # 三层颜色算了个白算（见 pet_texture.build_detail_bake_shader）。
    # 修掉之后，这些图案画进一张 256² 的贴花里，比几何精确得多，面数还省下来。
    shapes = [
        # 眼球不要拉长。y 方向 ×1.10 那版的下缘会插进吻部球体，
        # 交线在浅色吻部上留下两道深色竖痕，看着像泪痕。
        #
        # 分辨率单独抬高（build_skeleton.EYE_RES）：默认那档在脸上读成八边形。
        sphere("head", "pet_detail", (sign * ex, ey, ez), (eye_r,) * 3, res=EYE_RES)
        for sign in (1, -1)
    ]

    shapes += [
        sphere("jaw", "pet_detail", nose, (nose_r, nose_r * 0.82, nose_r * 0.88)),
        # 嘴：从鼻下往两侧下方各一段锥台，凑成一个浅浅的「w」。
        #
        # z 必须落在吻部**表面**上，而且这个 z **只能量，不能估**。
        # 融合用的体素重构 + 4 次平滑会把表面往里收，收多少算不出来；
        # 而头改成 Q 版大球之后吻部整个挪了位置。
        # `_research/probe-muzzle.py` 量出来的实际前表面：
        #   Cocos y 1.20–1.32 → z 0.714    （吻部最前那一带）
        #   Cocos y 1.14–1.20 → z 0.665    （往下急速收回去）
        # 上一版嘴在 z=0.655、半深 0.015，两头整个埋在里面，渲出来是一团碎渣。
        #
        # 截面压 Y 不压 Z：要的是一条横线，而不是一根管子；深度得留满，
        # 不然露出表面的那一点点连一个像素都占不到。
        taper("jaw", "pet_detail", (0.0, my, mz), ( mx, my - 0.022, mz - 0.028),
              0.030, 0.016, (1, 0.55, 1.0)),
        taper("jaw", "pet_detail", (0.0, my, mz), (-mx, my - 0.022, mz - 0.028),
              0.030, 0.016, (1, 0.55, 1.0)),
    ]

    # 腮红是贴图上的事，不加面数——养成品类里最便宜的可爱来源，
    # 一块柔和的粉色圆斑，成本是两行数据。
    # 强度别给大，0.55 那版糊在颊侧像一片疹子，0.32 才是「有点血色」。
    blobs = [
        # 腮红强度从 0.32 提到 0.62：参考图里是**明确的粉色椭圆**，
        # 0.32 那版在游戏里几乎看不见。腮红是 Q 版可爱度里性价比最高的一项。
        ("blush",  ( cx, cy, cz), cheek_r, cheek_r * 0.8, 0.62, None),
        ("blush",  (-cx, cy, cz), cheek_r, cheek_r * 0.8, 0.62, None),
    ]

    # 五官顶点按「离哪个中心最近」取色。中心就是各片几何自己的位置，
    # 所以鼻子和嘴各自拿到鼻色，眼球拿到虹膜色作为贴花的底。
    features = [("nose", nose), ("nose", (0.0, my - 0.010, mz - 0.020))]
    features += [("iris", (sign * ex, ey, ez)) for sign in (1, -1)]

    # 贴花规格：(中心, 半径, 光轴)。左右眼的光轴各自镜像，
    # 但贴花的横轴取的是世界水平方向（见 pet_texture._axis_euler），
    # 所以星形高光在两只眼上位置一致，不会一只偏左一只偏右。
    eyes = [((sign * ex, ey, ez), eye_r,
             (sign * axis[0], axis[1], axis[2])) for sign in (1, -1)]

    return {"shapes": shapes, "blobs": blobs, "features": features, "eyes": eyes}


