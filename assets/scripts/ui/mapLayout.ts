/** 点是否落在矩形内 */
export function hit(r: Rect, x: number, y: number): boolean {
  return (
    x >= r.cx - r.w / 2 && x <= r.cx + r.w / 2 && y >= r.cy - r.h / 2 && y <= r.cy + r.h / 2
  );
}
