/** 中心原点、y 向上的矩形（cx/cy 是中心） */
export interface Rect {
  cx: number;
  cy: number;
  w: number;
  h: number;
}

/** 取左下角坐标，供 Graphics.roundRect 用 */
export function bl(r: Rect): [number, number] {
  return [r.cx - r.w / 2, r.cy - r.h / 2];
}

/** 分区形态。每种在 mapZones.ts 里都必须有实现，漏一个那块墙会空着 */
export type ZoneShape = 'alcove' | 'arch' | 'tent' | 'store' | 'open';

export interface Zone extends Rect {
  key: string;
  name: string;
  sub: string;
  shape: ZoneShape;
  /**
   * `resources/map/alcoves/` 下的真实美术图名；**空串表示用代码绘制**。
   *
   * 两条路径都必须出画面：有图时 Sprite 盖住代码绘制的结构，加载失败时
   * 代码绘制仍在（规则 `map-scroll-view`：任何一条路径都要出画面）。
   * 招牌与文字**始终由代码画**，不依赖图 —— 图里的字号/字体我们控制不了。
   */
  art: string;
  /**
   * 招牌牌面在**图里**的位置与尺寸，全部是「占图的比例」。
   *
   * 招牌现在画进分区图里了（每个分区的牌子材质随门面：浴室是嵌在木拱框上的
   * 木牌、花园是被藤蔓缠着的吊牌、育婴室是布质吊牌、护理室是店铺挂牌），
   * 代码只负责把文字叠到牌面上 —— 这是「各自融入」而不是「一块统一的棕木牌
   * 浮在三个不同门面上」的做法，竞品就是这样（证据：它两块牌面的取色不同、
   * 且花园的藤蔓和牌子有互相遮挡，代码分层画不出来）。
   *
   * ⚠️ **不是「白色牌面」，是「和小屋同色的平整横带」**（2026-09-16 改）。
   *
   * 之前的提示词要求「牌面必须是纯净的平涂奶白色」，模型照做，
   * 结果每个小屋上压着一块 89% 近白（L=247）的干净白板 ——
   * 用户的反馈是「为什么有一个白色的背景，竞品像是直接融入进去的」。
   * **那个错误约束是我为了「保证程序写字清楚」自己加的。**
   *
   * 竞品的做法：**没有独立牌面**，字直接压在小屋某个部位上，
   * 底色就是小屋本身的颜色（实测育婴室底 `#FDCDB8` 是帐篷粉、
   * 花园底 `#F9D996` 是藤蔓黄绿），靠白字 + 深棕描边保证可读。
   *
   * 现在的提示词改成「门楣处留一条与本分区同色系的平整横带」，
   * 横带明度落在 138~173（竞品那一档），不再是白板。
   *
   * **这些值必须从最终落位的图上量，不能照提示词里写的比例。**
   * 抠底会裁掉四周空白，裁多少取决于画面内容，四张图各不相同。
   * 量法：`node .build/scripts/find-band.mjs <图>`
   * （找上半部分**颜色方差最小的连续横带** —— 横带按要求没有装饰和纹理，
   * 所以方差最小。这比找近白可靠，因为横带已经不是白的了）。
   * **重出图之后必须重新量、回填这里**，否则文字会飘到横带之外。
   */
  plate?: {
    /** 牌面中心占图高的比例，从图的**顶部**往下算 */
    cy: number;
    /** 牌面中心占图宽的比例，0.5 是正中 */
    cx: number;
    /** 牌面宽度占图宽的比例，用来判断字放不放得下 */
    w: number;
  };
}

/** 舞台的所有关键位置，全部由可视尺寸算出 */
export interface StageLayout {
  /** 视口宽（一屏） */
  vw: number;
  vh: number;
  /**
   * 世界宽（比视口宽，可横向拖动）。
   * 房间的墙/地/分区都按这个宽度铺，**不是 vw** —— 用 vw 铺会在拖动后露出底色。
   */
  worldW: number;
  /** 横向可拖范围（MapRoot 的 x 取值区间） */
  minX: number;
  maxX: number;
  /** 舞台内容上沿（HUD 之下）。分区/挂件排布用这条线 */
  top: number;
  /**
   * 墙纸的真实上沿 = **屏幕最顶端**。
   *
   * 和 `top` 分开是因为两者职责不同：`top` 管内容排布（要避让 HUD），
   * 墙纸则要铺满整屏。用 `top` 画墙纸会在顶部留一条纯色空带 ——
   * 竞品的墙纸是一直铺到屏幕顶的，HUD 直接压在墙纸上。
   */
  wallTop: number;
  /** 舞台下沿（底部入口之上） */
  bottom: number;
  /** 墙与地的交界 y */
  wallBottom: number;
  /**
   * 墙上挂件带的下沿（= 分区壁龛顶部之上一点）。
   * `on: 'wall'` 的道具以这条线为基准往上排，**不能用 wallBottom** ——
   * 那样算出来的位置会落进分区壁龛里，窗户直接压在花园拱门上。
   */
  hangBottom: number;
  zones: Zone[];
  /** 楼梯（纯装饰，没有玩法，所以不是 Zone） */
  stair: Rect;
  /** 宠物站立的 y（脚底） */
  petY: number;
  /** 宠物可游走的 x 范围 */
  petMinX: number;
  petMaxX: number;
}

