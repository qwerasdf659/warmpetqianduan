/**
 * 家庭地图 · 单屏布局与配色。
 *
 * **单屏舞台，不滚动**（2026-09-14 定，推翻了原先「2160×3600 双向滚动」的方案）。
 * 换方案的原因只有一条：概念稿 `docs/地图概念稿-00-仿竞品布局.png` 的观感前提是
 * 「一屏看到整个房间」——洗浴间、花园、育婴室、护理室、楼梯、宠物、底部入口全在同一屏。
 * 大世界方案下一屏只能看到约 12% 的面积，分区之间隔着上千像素的空地板，
 * 于是每个分区都孤零零占满整屏，和概念稿完全读不成同一个东西。
 *
 * 坐标系：**全部用「屏幕中心为原点、y 向上」**，和 Cocos 节点一致。
 * 旧方案那套「世界左上原点 + rectLocal 转换」一起去掉了 —— 单屏下没有世界坐标，
 * 多一层转换只会多一处能算错的地方。
 *
 * 布局纪律（`fitWidth` 下可视高度随机型变，见规则 `client-cocos`）：
 * 顶部自上而下留 HUD、底部自下而上留入口，**中间剩下的才是舞台**。
 * 一律由 `computeLayout()` 现算，不写死任何 y。
 */

